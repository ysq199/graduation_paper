from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")

import matplotlib.pyplot as plt
import numpy as np
from PIL import Image


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Visualize ROI contour and surface features.")
    parser.add_argument("--features-json", type=Path, help="Feature summary JSON generated by extract_roi_features.py.")
    parser.add_argument("--mask", type=Path, help="Optional 2D ROI mask image.")
    parser.add_argument("--contour-csv", type=Path, help="Optional sampled contour CSV.")
    parser.add_argument("--point-features-csv", type=Path, help="Optional per-point surface feature CSV.")
    parser.add_argument("--output-dir", type=Path, required=True, help="Directory for generated figures.")
    parser.add_argument("--max-points", type=int, default=20000, help="Max points to draw from point feature CSV.")
    return parser.parse_args()


def read_csv_array(path: Path) -> tuple[list[str], np.ndarray]:
    with path.open("r", encoding="utf-8", newline="") as handle:
        reader = csv.reader(handle)
        header = next(reader)
        rows = [[float(value) for value in row] for row in reader if row]
    return header, np.asarray(rows, dtype=float)


def maybe_downsample(points: np.ndarray, max_points: int, seed: int = 11) -> np.ndarray:
    if len(points) <= max_points:
        return points
    rng = np.random.default_rng(seed)
    idx = rng.choice(len(points), size=max_points, replace=False)
    return points[idx]


def draw_contour_overlay(mask_path: Path, contour_csv: Path, output_dir: Path) -> Path:
    image = Image.open(mask_path).convert("L")
    _, contour = read_csv_array(contour_csv)
    mask = np.asarray(image) > 0
    fig, ax = plt.subplots(figsize=(8, 5), dpi=160)
    ax.imshow(image, cmap="gray")
    ax.contour(mask.astype(float), levels=[0.5], colors=["#d62728"], linewidths=1.2)
    if len(contour):
        step = max(len(contour) // 64, 1)
        ax.scatter(contour[::step, 0], contour[::step, 1], s=8, color="#ff7f0e", label="sampled points")
    ax.set_title("2D ROI contour overlay")
    ax.set_xlabel("x / px")
    ax.set_ylabel("y / px")
    if len(contour):
        ax.legend(loc="lower right")
    ax.set_aspect("equal")
    fig.tight_layout()
    out = output_dir / "roi_contour_overlay.png"
    fig.savefig(out)
    plt.close(fig)
    return out


def draw_projection(points: np.ndarray, x_col: int, y_col: int, x_label: str, y_label: str, output: Path) -> None:
    curvature = points[:, 6]
    boundary = points[:, 9] > 0.5
    fig, ax = plt.subplots(figsize=(7.5, 5.5), dpi=160)
    scatter = ax.scatter(points[:, x_col], points[:, y_col], c=curvature, s=3, cmap="viridis", alpha=0.75, linewidths=0)
    if boundary.any():
        ax.scatter(points[boundary, x_col], points[boundary, y_col], s=6, c="#d62728", alpha=0.95, linewidths=0, label="boundary candidates")
    ax.set_xlabel(x_label)
    ax.set_ylabel(y_label)
    ax.set_title(f"Surface feature projection ({x_label}-{y_label})")
    ax.set_aspect("equal", adjustable="box")
    fig.colorbar(scatter, ax=ax, label="local curvature")
    if boundary.any():
        ax.legend(loc="best")
    fig.tight_layout()
    fig.savefig(output)
    plt.close(fig)


def set_axes_equal(ax) -> None:
    ranges = np.array(
        [
            ax.get_xlim3d(),
            ax.get_ylim3d(),
            ax.get_zlim3d(),
        ],
        dtype=float,
    )
    centers = ranges.mean(axis=1)
    radius = 0.5 * np.max(ranges[:, 1] - ranges[:, 0])
    ax.set_xlim3d([centers[0] - radius, centers[0] + radius])
    ax.set_ylim3d([centers[1] - radius, centers[1] + radius])
    ax.set_zlim3d([centers[2] - radius, centers[2] + radius])


def draw_surface_3d(points: np.ndarray, output: Path, elev: float = 24, azim: float = -62, title: str = "3D surface point features") -> None:
    curvature = points[:, 6]
    boundary = points[:, 9] > 0.5
    fig = plt.figure(figsize=(8, 6), dpi=160)
    ax = fig.add_subplot(111, projection="3d")
    scatter = ax.scatter(points[:, 0], points[:, 1], points[:, 2], c=curvature, s=2, cmap="viridis", alpha=0.65)
    if boundary.any():
        ax.scatter(points[boundary, 0], points[boundary, 1], points[boundary, 2], c="#d62728", s=5, alpha=0.9)
    ax.view_init(elev=elev, azim=azim)
    ax.set_title(title)
    ax.set_xlabel("x")
    ax.set_ylabel("y")
    ax.set_zlabel("z")
    set_axes_equal(ax)
    fig.colorbar(scatter, ax=ax, shrink=0.65, label="local curvature")
    fig.tight_layout()
    fig.savefig(output)
    plt.close(fig)


def draw_surface_3d_multiview(points: np.ndarray, output: Path) -> None:
    curvature = points[:, 6]
    views = [
        (24, -62, "isometric"),
        (0, -90, "front"),
        (0, 0, "side"),
        (90, -90, "top"),
    ]
    fig = plt.figure(figsize=(10, 8), dpi=160)
    for index, (elev, azim, title) in enumerate(views, start=1):
        ax = fig.add_subplot(2, 2, index, projection="3d")
        scatter = ax.scatter(points[:, 0], points[:, 1], points[:, 2], c=curvature, s=1.6, cmap="viridis", alpha=0.7)
        ax.view_init(elev=elev, azim=azim)
        ax.set_title(title)
        ax.set_xlabel("x")
        ax.set_ylabel("y")
        ax.set_zlabel("z")
        set_axes_equal(ax)
    fig.colorbar(scatter, ax=fig.axes, shrink=0.55, label="local curvature")
    fig.suptitle("3D surface feature multiview", y=0.98)
    fig.savefig(output, bbox_inches="tight")
    plt.close(fig)


def draw_surface_3d_normals(points: np.ndarray, output: Path, max_arrows: int = 250) -> None:
    curvature = points[:, 6]
    if len(points) > max_arrows:
        rng = np.random.default_rng(23)
        arrow_idx = rng.choice(len(points), size=max_arrows, replace=False)
    else:
        arrow_idx = np.arange(len(points))

    xyz = points[arrow_idx, :3]
    normals = points[arrow_idx, 3:6]
    bbox = points[:, :3].max(axis=0) - points[:, :3].min(axis=0)
    arrow_length = max(float(np.linalg.norm(bbox)) * 0.025, 1e-6)

    fig = plt.figure(figsize=(8, 6), dpi=160)
    ax = fig.add_subplot(111, projection="3d")
    scatter = ax.scatter(points[:, 0], points[:, 1], points[:, 2], c=curvature, s=1.5, cmap="viridis", alpha=0.45)
    ax.quiver(
        xyz[:, 0],
        xyz[:, 1],
        xyz[:, 2],
        normals[:, 0],
        normals[:, 1],
        normals[:, 2],
        length=arrow_length,
        normalize=True,
        color="#d62728",
        linewidth=0.45,
        alpha=0.85,
    )
    ax.view_init(elev=24, azim=-62)
    ax.set_title("3D surface normals for viewpoint planning")
    ax.set_xlabel("x")
    ax.set_ylabel("y")
    ax.set_zlabel("z")
    set_axes_equal(ax)
    fig.colorbar(scatter, ax=ax, shrink=0.65, label="local curvature")
    fig.tight_layout()
    fig.savefig(output)
    plt.close(fig)


def write_summary(features_json: Path | None, output_dir: Path) -> Path | None:
    if not features_json:
        return None
    payload = json.loads(features_json.read_text(encoding="utf-8"))
    out = output_dir / "feature_summary.txt"
    lines = []
    for result in payload.get("results", []):
        lines.append(f"[{result.get('type')}]")
        for key, value in result.get("features", {}).items():
            lines.append(f"{key}: {value}")
        lines.append("")
    out.write_text("\n".join(lines), encoding="utf-8")
    return out


def main() -> int:
    args = parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    outputs: list[Path] = []

    if args.mask and args.contour_csv:
        outputs.append(draw_contour_overlay(args.mask, args.contour_csv, args.output_dir))

    if args.point_features_csv:
        header, points = read_csv_array(args.point_features_csv)
        expected = ["x", "y", "z", "nx", "ny", "nz", "curvature", "roughness", "boundary_score", "boundary_flag"]
        if header[: len(expected)] != expected:
            print(f"Unexpected point feature CSV header: {header}", file=sys.stderr)
            return 2
        points = maybe_downsample(points, args.max_points)
        draw_projection(points, 0, 1, "x", "y", args.output_dir / "surface_projection_xy.png")
        draw_projection(points, 0, 2, "x", "z", args.output_dir / "surface_projection_xz.png")
        draw_projection(points, 1, 2, "y", "z", args.output_dir / "surface_projection_yz.png")
        draw_surface_3d(points, args.output_dir / "surface_3d_curvature.png")
        draw_surface_3d(points, args.output_dir / "surface_3d_curvature_alt_view.png", elev=16, azim=35, title="3D surface point features (alternate view)")
        draw_surface_3d_multiview(points, args.output_dir / "surface_3d_multiview.png")
        draw_surface_3d_normals(points, args.output_dir / "surface_3d_normals.png")
        outputs.extend(
            [
                args.output_dir / "surface_projection_xy.png",
                args.output_dir / "surface_projection_xz.png",
                args.output_dir / "surface_projection_yz.png",
                args.output_dir / "surface_3d_curvature.png",
                args.output_dir / "surface_3d_curvature_alt_view.png",
                args.output_dir / "surface_3d_multiview.png",
                args.output_dir / "surface_3d_normals.png",
            ]
        )

    summary = write_summary(args.features_json, args.output_dir)
    if summary:
        outputs.append(summary)

    for output in outputs:
        print(output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
